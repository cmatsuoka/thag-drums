#!/usr/bin/env python3
"""generate-wordmarks.py - cut the printed words of the panel into outlines.

The panel prints a handful of words: the name of every module and the
mark at the foot of every plate. They are set in Futura W02 Light, a
commercial face of Linotype, so the panel does not ship the face: the
words are cut here into SVG outlines and the panel draws the outlines.
The face carries fsType 0 in its OS/2 table, installable embedding, so a
document that carries the outlines may be distributed.

The outlines are drawn on the line box of the face, one em high, with the
baseline where the browser would put it, so an outline is a drop-in for
the text it replaces: the same box, the same line, the same place on the
plate.

Usage:
    python3 scripts/generate-wordmarks.py [path/to/FuturaW02-Light.woff2]

Needs fontTools and uharfbuzz. It is not part of the build: the file it
writes is committed.
"""

import sys
import tempfile
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = Path(
    sys.argv[1] if len(sys.argv) > 1 else ROOT / "vendor/fonts/FuturaW02-Light.woff2"
)
OUT = ROOT / "src/ui/wordmark-paths.ts"

# The words the panel prints, and the tracking of each in em. The names of
# the modules are set tight, so that the letters stand closer together; the
# mark is tracked out like the logo of the machine.
WORDS = {
    "BASS": -0.025,
    "SNARE": -0.025,
    "TOM 1": -0.025,
    "TOM 2": -0.025,
    "TOM 3": -0.025,
    "HI HAT": -0.025,
    "CYMBAL": -0.025,
    "THAG-V": 0.18,
}


def cut(font, path, word, tracking):
    """The outline of a word, in the em of the face."""
    upem = font["head"].unitsPerEm
    ascent = font["hhea"].ascent
    descent = -font["hhea"].descent

    # The line box is one em, and the browser puts the baseline where the
    # half-leading leaves it.
    baseline = ascent + (upem - (ascent + descent)) / 2

    face = hb.Face(hb.Blob.from_file_path(str(path)))
    shaped = hb.Font(face)
    shaped.scale = (upem, upem)
    buffer = hb.Buffer()
    buffer.add_str(word)
    buffer.guess_segment_properties()
    hb.shape(shaped, buffer)

    order = font.getGlyphOrder()
    glyphs = font.getGlyphSet()
    pen = SVGPathPen(glyphs)

    x = 0.0
    count = len(buffer.glyph_infos)
    for index, (info, position) in enumerate(
        zip(buffer.glyph_infos, buffer.glyph_positions)
    ):
        name = order[info.codepoint]
        if name in glyphs:
            # The face is drawn with the y axis up and the panel with the
            # y axis down: the word is turned over, and the baseline of
            # the line box comes with it.
            turned = TransformPen(pen, (1, 0, 0, -1, 0, baseline))
            placed = TransformPen(turned, (1, 0, 0, 1, x + position.x_offset, 0))
            glyphs[name].draw(placed)
        x += position.x_advance
        if index < count - 1:
            x += tracking * upem

    return pen.getCommands(), x, upem


def main():
    if not FONT.exists():
        raise SystemExit(f"the face is not there: {FONT}")

    font = TTFont(FONT)
    upem = font["head"].unitsPerEm

    lines = [
        "/*",
        " * The words the panel prints, cut into outlines.",
        " *",
        " * Generated by scripts/generate-wordmarks.py - do not edit by hand.",
        " * The face is Futura W02 Light; the panel ships the outlines and",
        " * not the face. Each outline is drawn on the line box of the face,",
        " * one em high, so it stands where the text would stand.",
        " */",
        "",
        "export interface Wordmark {",
        "  /** The box of the word, in the em of the face. */",
        "  readonly viewBox: string;",
        "  /** The outline of the word. */",
        "  readonly path: string;",
        "}",
        "",
        "export const WORDMARKS: Readonly<Record<string, Wordmark>> = {",
    ]

    with tempfile.TemporaryDirectory() as scratch:
        # HarfBuzz reads the tables of a plain font, and the face ships as
        # a WOFF2: it is turned back into one for the shaping.
        plain = Path(scratch) / "face.ttf"
        font.flavor = None
        font.save(plain)

        for word, tracking in WORDS.items():
            path, width, upem = cut(font, plain, word, tracking)
            box = f"0 0 {width:.0f} {upem}"
            lines.append(f'  "{word}": {{')
            lines.append(f'    viewBox: "{box}",')
            lines.append(f'    path: "{path}",')
            lines.append("  },")

    lines.append("};")
    lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(WORDS)} words)")


if __name__ == "__main__":
    main()
